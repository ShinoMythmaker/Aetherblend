"""FFXIV player modules, persistent generation toggles, and curated UI layout."""

import bpy

from ...definitions import Template
from ...rigify.settings import BoneCollection
from ..modules import arms, clothing, ears, face, general, genitals, hair, hands, legs, spine, tail, toes


class AETHER_PG_ffxiv_player_toggles(bpy.types.PropertyGroup):
    """Generation toggles belonging to the FFXIV player template."""

    ears: bpy.props.EnumProperty(
        name="Ears",
        items=[
            ("DEFAULT", "Default", "One controllable bone per ear", 0),
            ("NONE", "None", "Do not generate ears", 1),
            ("VIERA", "Viera", "Default ear controls and the selected Viera ear chains", 2),
        ],
        default="DEFAULT",
    )  # type: ignore
    viera_variant: bpy.props.EnumProperty(
        name="Eartype",
        description="Viera ear chains generated alongside available default ear controls",
        items=[
            ("A", "A", "Viera ears using j_zera bones"),
            ("B", "B", "Viera ears using j_zerb bones"),
            ("C", "C", "Viera ears using j_zerc bones"),
            ("D", "D", "Viera ears using j_zerd bones"),
        ],
        default="A",
    )  # type: ignore
    ivcs: bpy.props.EnumProperty(
        name="IVCS",
        description="Generate IVCS fingers and toes when their source bones are available",
        items=[
            ("AUTO", "Auto", "Use IVCS fingers and toes when complete source chains are present"),
            ("ON", "On", "Enable IVCS; fall back to standard fingers if IVCS tips are missing"),
            ("OFF", "Off", "Use standard fingers and do not generate IVCS toes"),
        ],
        default="AUTO",
    )  # type: ignore
    sex: bpy.props.EnumProperty(
        name="Sex",
        description="Genital controls to generate when IVCS is enabled",
        items=[
            ("MALE", "Male", "Generate only male anatomy", 1),
            ("FEMALE", "Female", "Generate only female anatomy", 2),
            ("OFF", "Off", "Do not generate genital controls", 0),
        ],
        default="OFF",
    )  # type: ignore
    mouth: bpy.props.EnumProperty(
        name="Mouth",
        description="Mouth controls generated by the face module",
        items=[("AUTOMATIC", "Automatic", "Automated jaw and lip chains"), ("MANUAL", "Manual", "Independent mouth controls")],
        default="AUTOMATIC",
    )  # type: ignore


def get_ui_layout(toggles: bpy.types.PropertyGroup | None) -> list[BoneCollection]:
    """Build the FFXIV collection layout for the selected sex and IVCS mode."""
    if toggles is None:
        raise ValueError("The FFXIV UI layout requires template toggles")
    if toggles.sex not in {"OFF", "MALE", "FEMALE"}:
        raise ValueError(f"Unknown sex mode: {toggles.sex}")
    nsfw = toggles.sex != "OFF" and toggles.ivcs != "OFF"
    layout = [
        BoneCollection("Hair", ui=True, color_set="Head", row_index=1, visible=False),
        BoneCollection("Accessory", ui=True, color_set="Head", row_index=1, visible=False),
        BoneCollection("Eyes (Macro)", ui=True, color_set="Face_Primary", row_index=3),
        BoneCollection("Face (Primary)", ui=True, color_set="Face_Primary", row_index=4),
        BoneCollection("Face (Secondary)", ui=True, color_set="Face_Secondary", row_index=4, visible=False),
        BoneCollection("Face (Misc)", ui=True, color_set="Face_Secondary", row_index=5, visible=False),
        BoneCollection("Head", ui=True, color_set="Head", row_index=7),
        BoneCollection("Torso", ui=True, color_set="Torso", row_index=8),
        BoneCollection("Torso (Tweak)", ui=True, color_set="Torso_Tweak", row_index=9, title="Tweak", visible=False),
        BoneCollection("Arm.L (IK)", ui=True, color_set="IK_Left", row_index=11, title="Arm IK.L"),
        BoneCollection("Arm.R (IK)", ui=True, color_set="IK_Right", row_index=11, title="Arm IK.R"),
        BoneCollection("Arm.L (FK)", ui=True, color_set="FK_Left", row_index=12, title="Arm FK.L", visible=False),
        BoneCollection("Arm.R (FK)", ui=True, color_set="FK_Right", row_index=12, title="Arm FK.R", visible=False),
        BoneCollection("Arm.L (Tweak)", ui=True, color_set="Tweak_Left", row_index=13, title="Tweak.L", visible=False),
        BoneCollection("Arm.R (Tweak)", ui=True, color_set="Tweak_Right", row_index=13, title="Tweak.R", visible=False),
        BoneCollection("Fingers.L", ui=True, color_set="Fingers_Left", row_index=15, visible=False),
        BoneCollection("Fingers.R", ui=True, color_set="Fingers_Right", row_index=15, visible=False),
        BoneCollection("Leg.L (IK)", ui=True, color_set="IK_Left", row_index=17, title="Leg IK.L"),
        BoneCollection("Leg.R (IK)", ui=True, color_set="IK_Right", row_index=17, title="Leg IK.R"),
        BoneCollection("Leg.L (FK)", ui=True, color_set="FK_Left", row_index=18, title="Leg FK.L", visible=False),
        BoneCollection("Leg.R (FK)", ui=True, color_set="FK_Right", row_index=18, title="Leg FK.R", visible=False),
        BoneCollection("Leg.L (Tweak)", ui=True, color_set="Tweak_Left", row_index=19, title="Tweak.L", visible=False),
        BoneCollection("Leg.R (Tweak)", ui=True, color_set="Tweak_Right", row_index=19, title="Tweak.R", visible=False),
        BoneCollection("Toes.L", ui=True, color_set="IVCS", row_index=21, title="Toes.L", visible=False),
        BoneCollection("Toes.R", ui=True, color_set="IVCS", row_index=21, title="Toes.R", visible=False),
        BoneCollection("Skirt", ui=True, color_set="Head", row_index=23, visible=False),
        BoneCollection("Tail", ui=True, color_set="Torso_Tweak", row_index=25),
    ]
    if nsfw:
        if toggles.sex == "MALE":
            layout.append(BoneCollection("Genitals (Male)", ui=True, color_set="IVCS", row_index=27, visible=False))
        if toggles.sex == "FEMALE":
            layout.append(BoneCollection("Genitals (Female)", ui=True, color_set="IVCS", row_index=27, visible=False))
    layout.extend(
        [
            BoneCollection("Original", ui=True, row_index=29 if nsfw else 27, visible=False),
            BoneCollection("Linked", ui=True, color_set="Torso_Tweak", row_index=30 if nsfw else 29, visible=False),
            BoneCollection("Unlinked", ui=True, color_set="IVCS", row_index=30 if nsfw else 29, visible=False),
            BoneCollection("LINK", ui=True, color_set="Torso", row_index=31 if nsfw else 30, visible=False),
            BoneCollection("MCH", ui=True, row_index=31 if nsfw else 30, visible=False),
            BoneCollection("DEF", ui=True, row_index=31 if nsfw else 30, visible=False),
            BoneCollection("ORG", ui=True, row_index=31 if nsfw else 30, visible=False),
            BoneCollection("Root", ui=True, row_index=33 if nsfw else 32, visible=True),
        ]
    )
    return layout


FFXIV = Template(
    name="FFXIV",
    toggles=AETHER_PG_ffxiv_player_toggles,
    toggle_visibility={
        "sex": lambda toggles: toggles.ivcs in {"AUTO", "ON"},
        "viera_variant": lambda toggles: toggles.ears == "VIERA",
    },
    ui_layout=get_ui_layout,
    modules=[
        ears.ffxiv_player,
        hair.ffxiv_player,
        face.ffxiv_player,
        spine.ffxiv_player,
        arms.ffxiv_player,
        hands.ffxiv_player,
        legs.ffxiv_player,
        toes.ffxiv_player,
        clothing.ffxiv_player,
        tail.ffxiv_player,
        genitals.ffxiv_player,
        general.ffxiv_player,
    ],
)
